// Fixed-version real CLI experiment planning for the three required 对照 groups.
// This module never calls a model: it creates a throwaway fixture, freezes the
// owner verifier content hash, builds the three groups and checks hard limits.
// The paid execution path remains gated by explicit operator authorization.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export type ExperimentGroupId = 'single' | 'parallel-independent' | 'collaborative';

export interface ExperimentAgent {
  id: string;
  name: string;
  provider: string;
  enabled: boolean;
  connectionMode?: string;
  executionMode?: string;
  workspaceMode?: 'isolated' | 'source';
  executable?: string;
  version?: string;
}

export interface ExperimentLimits {
  maxMinutes: number;
  maxActivations: number;
  maxCostUsd: number;
}

export interface ExperimentGroup {
  id: ExperimentGroupId;
  label: string;
  agents: string[];
  taskCount: number;
  expectedActivations: number;
  requiresIntegration: boolean;
  steps: string[];
}

export interface ExperimentPlan {
  ready: boolean;
  modelRequests: 0;
  fixture: {projectPath: string; verifierHash: string; fixtureHash: string};
  verifier: {command: string; source: string; hash: string};
  limits: ExperimentLimits;
  groups: ExperimentGroup[];
  blockers: string[];
  warnings: string[];
}

export const DEFAULT_EXPERIMENT_LIMITS: ExperimentLimits = {maxMinutes: 30, maxActivations: 12, maxCostUsd: 5};

const realProviders = new Set(['codex', 'claude', 'deepseek', 'api', 'a2a']);

export function sha256(value: string | Buffer): string {
  return createHash('sha256').update(value).digest('hex');
}

/** Stable owner-controlled verifier, never generated by the tested Agent. */
export const EXPERIMENT_VERIFIER_SOURCE = `import {readFileSync} from 'node:fs';
const value = JSON.parse(readFileSync('order-query.json', 'utf8'));
if (value.query !== 'SELECT * FROM orders WHERE id = ?' || value.parameterized !== true) process.exit(1);
if (!value.tests || value.tests < 1) process.exit(1);
console.log('order-query-contract-ok');
`;

export function createExperimentFixture(root: string): ExperimentPlan['fixture'] & {verifier: ExperimentPlan['verifier']} {
  const projectPath = join(root, 'order-query-fixture');
  mkdirSync(projectPath, {recursive: true});
  writeFileSync(join(projectPath, 'README.md'), '# order query fixture\n');
  writeFileSync(join(projectPath, 'baseline.txt'), 'baseline\n');
  const verifierDir = join(root, 'owner-verifier');
  mkdirSync(verifierDir, {recursive: true});
  writeFileSync(join(verifierDir, 'verify-order-query.mjs'), EXPERIMENT_VERIFIER_SOURCE);
  const fixtureFiles = ['README.md', 'baseline.txt'].map(name => [name, sha256(readFileSync(join(projectPath, name)))]);
  return {
    projectPath,
    verifierHash: sha256(EXPERIMENT_VERIFIER_SOURCE),
    fixtureHash: sha256(JSON.stringify(fixtureFiles)),
    verifier: {command: 'node owner-verifier/verify-order-query.mjs', source: EXPERIMENT_VERIFIER_SOURCE, hash: sha256(EXPERIMENT_VERIFIER_SOURCE)}
  };
}

export function planThreeGroupExperiment(input: {agents: readonly ExperimentAgent[]; fixture: ReturnType<typeof createExperimentFixture>; limits?: Partial<ExperimentLimits>}): ExperimentPlan {
  const limits = {...DEFAULT_EXPERIMENT_LIMITS, ...input.limits};
  const blockers: string[] = [], warnings: string[] = [];
  const selectable = input.agents.filter(agent => agent.enabled && realProviders.has(agent.provider) && agent.connectionMode !== 'external' && agent.connectionMode !== 'attach');
  if (selectable.length < 2) blockers.push('需要至少两个已启用的真实 CLI/API Agent（demo、external、attach 不计入真实实验）');
  if (!Number.isFinite(limits.maxMinutes) || limits.maxMinutes <= 0) blockers.push('maxMinutes 必须是正数');
  if (!Number.isFinite(limits.maxActivations) || limits.maxActivations < 3) blockers.push('maxActivations 至少为 3');
  if (!Number.isFinite(limits.maxCostUsd) || limits.maxCostUsd <= 0) blockers.push('maxCostUsd 必须是正数');
  const first = selectable[0], second = selectable[1];
  const agentIds = [first?.id ?? 'agent_a', second?.id ?? 'agent_b'];
  const groups: ExperimentGroup[] = [
    {
      id: 'single', label: '单 Agent', agents: [agentIds[0]], taskCount: 1, expectedActivations: 1, requiresIntegration: false,
      steps: ['单 Agent 在独立 fixture 实现订单查询契约', 'owner 验收器对产物执行同一冻结检查', '记录墙钟、Run 耗时、known/unknown 成本']
    },
    {
      id: 'parallel-independent', label: '两个独立 Agent 简单并行', agents: agentIds, taskCount: 2, expectedActivations: 2, requiresIntegration: false,
      steps: ['两个 Agent 各自任务、独立 cwd、不共享中间产物', '用真实 adapter 启动/结束时间证明执行区间重叠', 'owner 分别验收两份产物']
    },
    {
      id: 'collaborative', label: '完整协作与受控集成', agents: agentIds, taskCount: 2, expectedActivations: 3, requiresIntegration: true,
      steps: ['上游 Agent 完成任务并生成 patch', '下游 Agent 在冻结依赖产物基础上复核/修改', 'owner 验收后走 integration 组合与 apply journal']
    }
  ];
  const expectedActivations = groups.reduce((sum, group) => sum + group.expectedActivations, 0);
  if (expectedActivations > limits.maxActivations) blockers.push(`计划激活数 ${expectedActivations} 超过上限 ${limits.maxActivations}`);
  if (first && first.executionMode === 'host' && first.workspaceMode === 'source') warnings.push('host-source 为串行执行，不能用来证明并行；并行组应使用 isolated/sandbox');
  return {
    ready: blockers.length === 0,
    modelRequests: 0,
    fixture: {projectPath: input.fixture.projectPath, verifierHash: input.fixture.verifierHash, fixtureHash: input.fixture.fixtureHash},
    verifier: input.fixture.verifier,
    limits,
    groups,
    blockers: [...new Set(blockers)],
    warnings: [...new Set(warnings)]
  };
}

/** Parse an ISO interval; invalid/absent evidence is explicitly unknown. */
export function executionOverlap(a: {startedAt?: string; finishedAt?: string}, b: {startedAt?: string; finishedAt?: string}): {known: boolean; overlapMs: number} {
  const parse = (value?: string) => value ? Date.parse(value) : Number.NaN;
  const aStart = parse(a.startedAt), aEnd = parse(a.finishedAt), bStart = parse(b.startedAt), bEnd = parse(b.finishedAt);
  if (![aStart, aEnd, bStart, bEnd].every(Number.isFinite)) return {known: false, overlapMs: 0};
  return {known: true, overlapMs: Math.max(0, Math.min(aEnd, bEnd) - Math.max(aStart, bStart))};
}

/** Unknown cost is not zero: return both known total and unknown count/list. */
export function summarizeExperimentCosts(entries: readonly {costUsd?: number; runId?: string}[]): {knownUsd: number; unknownCount: number; unknownRuns: string[]} {
  let knownUsd = 0;
  const unknownRuns: string[] = [];
  for (const entry of entries) {
    if (typeof entry.costUsd === 'number' && Number.isFinite(entry.costUsd)) knownUsd += entry.costUsd;
    else unknownRuns.push(entry.runId ?? 'unknown');
  }
  return {knownUsd, unknownCount: unknownRuns.length, unknownRuns};
}
