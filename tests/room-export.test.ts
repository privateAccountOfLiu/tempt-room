import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createApp } from '../apps/server/src/app.ts';
import { uid } from '../apps/server/src/store.ts';

const parent = resolve('.state/test-data');
test('owner can export one room as events and metadata', async t => {
  mkdirSync(parent, {recursive: true});
  const root = mkdtempSync(join(parent, 'room-export-'));
  const {app, store, service} = await createApp({root, startWorker: false, token: 'export-owner'});
  t.after(async () => { await app.close(); rmSync(root, {recursive: true, force: true}); });
  const roomId = store.rooms()[0].id;
  service.execute({version: '0.1', commandId: uid(), roomId, type: 'message.send', payload: {text: 'export me'}});
  const artifact = {id: 'artifact_export1', roomId, name: 'report.txt', kind: 'file' as const, mediaType: 'text/plain', size: 5, createdAt: new Date().toISOString()};
  mkdirSync(join(root, 'artifacts'), {recursive: true}); writeFileSync(join(root, 'artifacts', artifact.id), 'hello');
  store.event(roomId, 'artifact.created', {id: 'owner', kind: 'human'}, {artifact});
  service.execute({version: '0.1', commandId: uid(), roomId, type: 'message.send', payload: {text: 'token ' + ['s','k-','abcdefghijklmnopqrstuvwx'].join('')}});
  const headers = {host: '127.0.0.1:4317', authorization: 'Bearer export-owner', 'room-protocol-version': '0.1'};
  const exported = await app.inject({url: `/api/rooms/${roomId}/export`, headers});
  assert.equal(exported.statusCode, 200);
  const body = exported.json() as {version: string; room: {id: string}; events: {type: string}[]; exportHash: string};
  assert.equal(body.room.id, roomId);
  assert.ok(body.events.some(event => event.type === 'chat.message.created'));
  assert.match(body.exportHash, /^[a-f0-9]{64}$/i);
  const repeated = await app.inject({url: `/api/rooms/${roomId}/export`, headers});
  assert.equal(repeated.json().exportHash, body.exportHash);
  const secretArtifact = {id: 'artifact_secret1', roomId, name: 'secret.txt', kind: 'file' as const, mediaType: 'text/plain', size: 40, createdAt: new Date().toISOString()};
  writeFileSync(join(root, 'artifacts', secretArtifact.id), 'key ' + ['s','k-','abcdefghijklmnopqrstuvwx'].join(''));
  store.event(roomId, 'artifact.created', {id: 'owner', kind: 'human'}, {artifact: secretArtifact});
  const packaged = await app.inject({url: `/api/rooms/${roomId}/export?includeArtifacts=1&redact=1`, headers});
  const item = packaged.json().artifacts[0];
  assert.equal(item.artifact.id, artifact.id);
  const secretItem = packaged.json().artifacts.find((entry: any) => entry.artifact.id === secretArtifact.id);
  assert.doesNotMatch(Buffer.from(secretItem.contentBase64, 'base64').toString('utf8'), /abcdefghijklmnopqrstuvwx/);
  assert.match(Buffer.from(secretItem.contentBase64, 'base64').toString('utf8'), /\[REDACTED\]/);
  assert.ok(packaged.json().redactions > 0);
  assert.equal(Buffer.from(item.contentBase64, 'base64').toString('utf8'), 'hello');
  assert.match(item.contentHash, /^[a-f0-9]{64}$/i);
  const redacted = await app.inject({url: `/api/rooms/${roomId}/export?redact=1`, headers});
  const redactedBody = redacted.json() as {redactions: number; events: {payload: any}[]};
  assert.ok(redactedBody.redactions > 0);
  assert.ok(redactedBody.events.some(event => JSON.stringify(event.payload).includes('[REDACTED]')));
  assert.equal((await app.inject({url: `/api/rooms/${roomId}/export`, headers: {host: headers.host, 'room-protocol-version': '0.1'}})).statusCode, 401);
});
